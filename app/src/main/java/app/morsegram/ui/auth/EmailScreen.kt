@Composable
fun EmailScreen(onCodeRequested: (email: String) -> Unit) {
    var email by rememberSaveable { mutableStateOf("") }

    Scaffold { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(24.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp, Alignment.CenterVertically),
        ) {
            Text("Morsegram", style = MaterialTheme.typography.headlineLarge)
            Text("Введи почту — пришлём на неё код для входа.")
            OutlinedTextField(
                value = email,
                onValueChange = { email = it },
                label = { Text("Email") },
                singleLine = true,
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Email),
                modifier = Modifier.fillMaxWidth(),
            )
            Button(
                onClick = { onCodeRequested(email.trim()) },
                enabled = isValidEmail(email),
                modifier = Modifier.fillMaxWidth(),
            ) {
                Text("Получить код")
            }
        }
    }
}
