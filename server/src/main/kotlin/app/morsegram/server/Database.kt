package app.morsegram.server

import com.zaxxer.hikari.HikariConfig
import com.zaxxer.hikari.HikariDataSource
import java.sql.Connection
import java.sql.PreparedStatement
import java.sql.ResultSet
import java.sql.Statement
import javax.sql.DataSource

/** Тонкая обёртка над JDBC: пул соединений, создание таблиц и пара помощников для запросов. */
class Database(private val dataSource: DataSource) {

    fun migrate() = transaction { connection ->
        connection.createStatement().use { st ->
            SCHEMA.forEach { st.execute(it) }
        }
    }

    fun <T> transaction(block: (Connection) -> T): T = dataSource.connection.use { connection ->
        connection.autoCommit = false
        try {
            block(connection).also { connection.commit() }
        } catch (e: Throwable) {
            connection.rollback()
            throw e
        }
    }

    companion object {
        fun connect(url: String, user: String, password: String): Database {
            val config = HikariConfig().apply {
                jdbcUrl = url
                username = user
                this.password = password
                maximumPoolSize = 10
            }
            return Database(HikariDataSource(config))
        }

        private val SCHEMA = listOf(
            """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email VARCHAR(254) NOT NULL UNIQUE,
                password_hash VARCHAR(100) NOT NULL,
                verified BOOLEAN NOT NULL DEFAULT FALSE,
                display_name VARCHAR(64) NOT NULL DEFAULT '',
                nickname VARCHAR(32),
                nickname_key VARCHAR(32) UNIQUE,
                bio VARCHAR(140) NOT NULL DEFAULT '',
                created_at BIGINT NOT NULL
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS email_codes (
                user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                code_hash VARCHAR(64) NOT NULL,
                expires_at BIGINT NOT NULL,
                attempts INT NOT NULL DEFAULT 0,
                sent_at BIGINT NOT NULL
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS sessions (
                token_hash VARCHAR(64) PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                created_at BIGINT NOT NULL
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS contacts (
                owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                contact_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                PRIMARY KEY (owner_id, contact_id)
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                body TEXT NOT NULL,
                created_at BIGINT NOT NULL
            )
            """,
            "CREATE INDEX IF NOT EXISTS messages_recipient ON messages (recipient_id, id)",
        )
    }
}

fun Connection.update(sql: String, vararg args: Any?): Int =
    prepareStatement(sql).use { it.bind(args).executeUpdate() }

fun Connection.insert(sql: String, vararg args: Any?): Long =
    prepareStatement(sql, Statement.RETURN_GENERATED_KEYS).use { st ->
        st.bind(args).executeUpdate()
        st.generatedKeys.use { keys ->
            keys.next()
            keys.getLong(1)
        }
    }

fun <T> Connection.query(sql: String, vararg args: Any?, map: (ResultSet) -> T): List<T> =
    prepareStatement(sql).use { st ->
        st.bind(args).executeQuery().use { rs ->
            buildList { while (rs.next()) add(map(rs)) }
        }
    }

private fun PreparedStatement.bind(args: Array<out Any?>): PreparedStatement {
    args.forEachIndexed { i, value -> setObject(i + 1, value) }
    return this
}
